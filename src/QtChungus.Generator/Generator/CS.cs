using System.Runtime.InteropServices;

public static partial class Generator
{
    private class OldFileInfo
    {
        public string ClassName { get; }
        public string? InheritanceRegion { get; }
        public string? MembersRegion { get; }
        public OldFileInfo(string fullPath)
        {
            ClassName = Path.GetFileNameWithoutExtension(fullPath);

            Dictionary<string, string> userCode;
            using (var reader = File.OpenText(fullPath))
            {
                userCode = ExtractUserCode(reader);
            }
            if (userCode.TryGetValue("Inheritance", out var inheritanceRegion))
            {
                InheritanceRegion = inheritanceRegion;
                userCode.Remove("Inheritance");
            }
            if (userCode.TryGetValue("Members", out var membersRegion))
            {
                MembersRegion = membersRegion;
                userCode.Remove("Members");
            }
            if (userCode.Count > 0)
            {
                throw new InvalidOperationException($"Unexpected regions in {ClassName}: {string.Join(", ", userCode.Keys)}");
            }
        }
    }

    public static void GenerateCs(string folderPath)
    {
        var oldFiles = Directory.EnumerateFiles(folderPath)
            .Where(x => Path.GetExtension(x) is ".cs")
            .Select(x => new OldFileInfo(x))
            .ToDictionary(x => x.ClassName, x => x);

        var newFiles = new Dictionary<string, string>();
        foreach (var type in QObjectType.All)
        {
            var filePath = Path.Combine(folderPath, Path.ChangeExtension(type.CsName, ".cs"));
            var oldFileExists = oldFiles.TryGetValue(type.CsName, out var oldFileInfo);
            using (var writer = File.CreateText(filePath))
            {
                GenerateCsClass(writer, type, oldFiles.GetValueOrDefault(type.CsName));
            }
            if (oldFileExists)
            {
                oldFiles.Remove(type.CsName);
            }
        }
        if (oldFiles.Count > 0)
        {
            Console.WriteLine("Leftover CS files:");
            foreach (var className in oldFiles.Keys)
            {
                Console.WriteLine($"{className}.cs");
            }
        }
    }

    private static Dictionary<string, string> ExtractUserCode(StreamReader reader)
    {
        var result = new Dictionary<string, List<string>>();
        var currentRegionName = (string?)null;
        while (!reader.EndOfStream)
        {
            var line = reader.ReadLine()!;
            var trimmedLine = line.AsSpan().TrimStart();

            if (trimmedLine.StartsWith("#region"))
            {
                if (currentRegionName is not null)
                {
                    throw new NotSupportedException("Nested regions are not supported.");
                }
                currentRegionName = trimmedLine.Slice("#region".Length).Trim().ToString();
                continue;
            }

            if (trimmedLine.StartsWith("#endregion"))
            {
                if (currentRegionName is null)
                {
                    throw new InvalidOperationException("Negative region depth.");
                }
                currentRegionName = null;
                continue;
            }

            if (currentRegionName is not null)
            {
                ref var list = ref CollectionsMarshal.GetValueRefOrAddDefault(result, currentRegionName, out _);
                list ??= new();
                list.Add(line);
            }
        }
        return result.ToDictionary(x => x.Key, x => string.Join(Environment.NewLine, x.Value));
    }

    private static void GenerateCsClass(StreamWriter writer, QObjectType type, OldFileInfo? oldFileInfo)
    {
        writer.WriteLine(
"""
// Generated by QtChungus.Generator
// Read `readme.md` in containing folder before any modifications

namespace QtChungus;
"""
        );

        writer.WriteLine(
$$"""
public unsafe readonly record struct {{type.CsName}}(QObjectStar Handle)
#region Inheritance
{{oldFileInfo?.InheritanceRegion}}
#endregion
{
"""
        );

        foreach(var baseType in type.TypeHierarchy.Skip(1))
        {
            writer.WriteLine(
$$"""
    public static implicit operator {{baseType.CsName}}({{type.CsName}} source) => new(source.Handle);
    public static explicit operator {{type.CsName}}({{baseType.CsName}} source) => new(source.Handle);

"""
            );
        }

        writer.WriteLine(
"""
#nullable disable
"""
        );
        var methods = type.TypeHierarchy
            .SelectMany(x => x.Methods)
            .Where(x => x.Owner == type || x.Name != "@new") // Exclude base type constructors
            .OrderBy(x => x.Id)
            .ToArray();

        foreach (var method in methods)
        {
            var returnType = method.ReturnType?.CsName ?? "void";
            var signatureParameters = string.Join(", ", method.Parameters.Select(x => $"{x.Type.CsName} {x.Name}"));
            var stackallocParameters = string.Join(", ", method.Parameters.Select((x, i) => x.Type.MarshalToCsVariant(x.Name)));
            var accessModifier = method.Name == "@new" ? "private static" : "private";
            var thisParameter = method.Name == "@new" ? "default" : "this.Handle";
            writer.WriteLine(
$$"""
    {{accessModifier}} {{returnType}} {{method.Name}}({{signatureParameters}})
    {
        CVariant* parameters = stackalloc CVariant[] { {{stackallocParameters}} };
        QObjectStar.QcInvoke("{{method.Id}}", {{thisParameter}}, out var result, parameters);
"""
            );
            if (method.ReturnType is not null)
            {
                writer.WriteLine(
$$"""
        return {{method.ReturnType.MarshalFromCsVariant("result")}};
"""
                );
            }
            writer.WriteLine(
"""
    }
"""
            );
        }
        writer.WriteLine(
"""
#nullable restore
"""
        );
        writer.WriteLine(
$$"""

    #region Members
{{oldFileInfo?.MembersRegion}}
    #endregion
"""
        );
        writer.WriteLine(
"""
}
"""
        );
    }
}